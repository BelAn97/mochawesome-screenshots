/**
 * Compiles src/templates/*.mu (Handlebars) into src/generated/templates.ts,
 * which is then bundled by tsup together with the reporter runtime.
 */

import { mkdir, readFile, readdir, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import Handlebars from 'handlebars';

const templatesDir = fileURLToPath(new URL('../src/templates/', import.meta.url));
const outFile = fileURLToPath(new URL('../src/generated/templates.ts', import.meta.url));

const toCamelCase = (name) => name.replace(/-([a-z])/g, (_, char) => char.toUpperCase());

const files = await readdir(templatesDir);
const partialFiles = files.filter((f) => f.startsWith('_') && f.endsWith('.mu'));
const templateFiles = files.filter((f) => !f.startsWith('_') && f.endsWith('.mu'));

let code = `/* eslint-disable */
// @ts-nocheck
// Generated by scripts/build-templates.mjs from src/templates/*.mu. Do not edit.
import Handlebars from 'handlebars';
import { registerTemplateHelpers } from '../ts/templateHelpers.js';

registerTemplateHelpers();

`;

for (const file of partialFiles) {
  const source = await readFile(path.join(templatesDir, file), 'utf8');
  // Partial names keep the leading underscore: templates reference them as {{> _name}}.
  const name = path.basename(file, '.mu');
  const precompiled = Handlebars.precompile(source, { preventIndent: true });
  code += `Handlebars.registerPartial(${JSON.stringify(name)}, Handlebars.template(${precompiled}));\n\n`;
}

for (const file of templateFiles) {
  const source = await readFile(path.join(templatesDir, file), 'utf8');
  const name = toCamelCase(path.basename(file, '.mu'));
  const precompiled = Handlebars.precompile(source, { preventIndent: true });
  code += `export const ${name} = Handlebars.template(${precompiled});\n\n`;
}

await mkdir(path.dirname(outFile), { recursive: true });
await writeFile(outFile, code);
console.log(
  `templates: compiled ${partialFiles.length} partial(s) + ${templateFiles.length} template(s) -> src/generated/templates.ts`
);
